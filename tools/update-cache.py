"""Regenerate the precache file list and build fingerprint after editing application assets."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parents[1]
files=[root/'index.html',root/'manifest.webmanifest']
files+=sorted(p for p in(root/'assets').rglob('*')if p.is_file())
files += [root/'data/wordnet-vi.json', root/'data/WORDNET-NOTICE.txt']
digest=hashlib.sha256()
def canonical(file):
    data=file.read_bytes()
    return data.replace(b'\r\n',b'\n') if file.suffix in {'.css','.js','.html','.webmanifest','.svg','.json','.txt'} else data
for file in files:digest.update(file.relative_to(root).as_posix().encode());digest.update(canonical(file))
digest.update((root/'sw.js').read_bytes().replace(b'\r\n',b'\n'))
paths=['./'+p.relative_to(root).as_posix()for p in files]
content='// Generated by tools/update-cache.py. No dictionary in the initial shell.\n'
content+='self.TUTU_BUILD='+json.dumps(digest.hexdigest()[:16])+';\n'
content+='self.TUTU_PRECACHE='+json.dumps(paths,indent=2)+';\n'
content+='self.TUTU_DICTIONARY_REV='+json.dumps(hashlib.sha256((root/'data/dictionary.json.gz').read_bytes()).hexdigest()[:16])+';\n'
lexicon = sorted((root/'data/wordnet').glob('*.json.gz'))
lexicon_hash = hashlib.sha256()
for file in lexicon:
    lexicon_hash.update(file.name.encode());lexicon_hash.update(file.read_bytes())
content+='self.TUTU_LEXICON_REV='+json.dumps(lexicon_hash.hexdigest()[:16])+';\n'
content+='self.TUTU_LEXICON='+json.dumps(['./'+p.relative_to(root).as_posix() for p in lexicon],indent=2)+';\n'
(root/'precache-manifest.js').write_text(content,encoding='utf-8')
print(json.dumps({'build':digest.hexdigest()[:16],'shell_files':len(files),'shell_bytes':sum(p.stat().st_size for p in files)}))
